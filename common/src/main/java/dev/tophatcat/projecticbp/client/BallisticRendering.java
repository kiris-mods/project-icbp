package dev.tophatcat.projecticbp.client;

import dev.tophatcat.projecticbp.client.renderer.BallisticPenguinRenderer;
import dev.tophatcat.projecticbp.registry.BallisticEntityRegistry;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;

import java.util.function.BiConsumer;

public class BallisticRendering {

    public static void registerEntityRenderers(
        BiConsumer<EntityType<? extends Entity>, EntityRendererProvider> consumer) {
        consumer.accept(BallisticEntityRegistry.BALLISTIC_PENGUIN.get(), BallisticPenguinRenderer::new);
    }
}
